"use client";

import {
  AlertTriangle,
  BookOpen,
  CheckCircle2,
  ExternalLink,
  FileText,
  Info,
  Loader2,
  ShieldCheck,
  Sparkles,
} from "lucide-react";
import Link from "next/link";
import * as React from "react";

import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Separator } from "@/components/ui/separator";
import {
  downloadReportDocx,
  downloadReportPdf,
  type RecommendResponse,
} from "@/lib/api";
import { formatMs } from "@/lib/format";
import { cn } from "@/lib/utils";

/**
 * The RAG answer, with the things that make it trustworthy attached to it:
 * every citation, every warning, and the mode that produced it.
 *
 * `mode` is shown as a badge and not hidden. "extractive" means the answer is
 * assembled from retrieved clauses and quotes the corpus; "llm" means a model
 * wrote it. Those deserve different amounts of trust, and a UI that renders
 * both identically is asking the user to guess.
 */
export function AnswerPanel({ answer }: { answer: RecommendResponse }) {
  const isLlm = answer.mode === "llm";
  const [exportingFormat, setExportingFormat] = React.useState<"docx" | "pdf" | null>(null);
  const [exportError, setExportError] = React.useState<string | null>(null);

  async function handleExport(format: "docx" | "pdf") {
    setExportingFormat(format);
    setExportError(null);
    try {
      if (format === "docx") {
        await downloadReportDocx(answer);
      } else {
        await downloadReportPdf(answer);
      }
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : "Failed to generate report file.";
      setExportError(msg);
      setTimeout(() => setExportError(null), 5000);
    } finally {
      setExportingFormat(null);
    }
  }

  return (
    <Card>
      <CardHeader className="pb-3">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <CardTitle className="flex items-center gap-2 text-base">
            {isLlm ? (
              <Sparkles className="h-4 w-4 text-tricolor-saffron" />
            ) : (
              <BookOpen className="h-4 w-4 text-tricolor-saffron" />
            )}
            Answer
          </CardTitle>
          <div className="flex flex-wrap items-center gap-2">
            <Badge variant={isLlm ? "default" : "outline"}>
              {isLlm ? "Generated by LLM" : "Extracted from the standards"}
            </Badge>
            {answer.grounded ? (
              <Badge variant="success" className="gap-1">
                <CheckCircle2 className="h-3 w-3" />
                Verified against indexed evidence
              </Badge>
            ) : (
              <Badge variant="warning" className="gap-1">
                <AlertTriangle className="h-3 w-3" />
                Unverified standard reference
              </Badge>
            )}
            <span className="text-xs text-muted-foreground">{formatMs(answer.took_ms)}</span>
          </div>
        </div>
      </CardHeader>

      <CardContent className="space-y-4">
        <div className="whitespace-pre-line text-sm leading-relaxed">{answer.answer}</div>

        {answer.unsupported_citations.length > 0 ? (
          <div className="rounded-md border border-amber-300 bg-amber-50 p-3.5 text-sm text-amber-900 dark:border-amber-700/60 dark:bg-amber-950/40 dark:text-amber-200">
            <p className="flex items-center gap-2 font-semibold">
              <AlertTriangle className="h-4 w-4 shrink-0 text-amber-600 dark:text-amber-400" />
              Unverified Standard Reference
            </p>
            <div className="mt-1.5 space-y-1 text-xs leading-relaxed">
              {answer.unsupported_citations.map((desig) => (
                <p key={desig}>
                  The model mentioned <strong>{desig}</strong>, but this standard is not currently available in the indexed BIS knowledge base. Therefore, a verified citation cannot be provided.
                </p>
              ))}
            </div>
          </div>
        ) : null}

        {answer.citations.length > 0 ? (
          <>
            <Separator />
            <div className="space-y-2">
              <div className="flex items-center justify-between">
                <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground flex items-center gap-1.5">
                  <ShieldCheck className="h-3.5 w-3.5 text-emerald-600 dark:text-emerald-400" />
                  Verified Citations ({answer.citations.length})
                </p>
                <span className="text-[11px] text-muted-foreground">Verified against indexed evidence</span>
              </div>
              <ul className="grid gap-2 sm:grid-cols-2">
                {answer.citations.map((citation) => (
                  <li
                    key={citation.designation + citation.chunk_id}
                    className="rounded-lg border bg-muted/30 p-3"
                  >
                    <div className="flex items-start justify-between gap-2">
                      <Link
                        href={`/standards?q=${encodeURIComponent(citation.designation)}`}
                        className="font-mono text-sm font-semibold hover:text-tricolor-saffron hover:underline"
                      >
                        {citation.designation}
                      </Link>
                      {citation.is_current ? (
                        <Badge variant="success">Current</Badge>
                      ) : (
                        <Badge variant="warning">Superseded</Badge>
                      )}
                    </div>
                    <p className="mt-1 text-xs leading-snug text-muted-foreground">
                      {citation.title}
                    </p>
                    {citation.superseded_by ? (
                      <p className="mt-1 text-xs text-amber-700">
                        Replaced by {citation.superseded_by}
                      </p>
                    ) : null}
                    {citation.archive_url ? (
                      <a
                        href={citation.archive_url}
                        target="_blank"
                        rel="noreferrer noopener"
                        className="mt-1 inline-flex items-center gap-1 text-xs text-muted-foreground hover:text-foreground hover:underline"
                      >
                        Source document <ExternalLink className="h-3 w-3" />
                      </a>
                    ) : null}
                  </li>
                ))}
              </ul>
            </div>
          </>
        ) : null}

        {answer.warnings.length > 0 ? (
          <div className="rounded-md border border-amber-300 bg-amber-50 p-3 text-sm text-amber-900">
            <p className="flex items-center gap-2 font-medium">
              <AlertTriangle className="h-4 w-4" />
              Warnings
            </p>
            <ul className="mt-1 list-disc space-y-0.5 pl-5">
              {answer.warnings.map((warning) => (
                <li key={warning}>{warning}</li>
              ))}
            </ul>
          </div>
        ) : null}

        {answer.compliance ? (
          <div className="rounded-md border border-emerald-200 bg-emerald-50 p-3 text-sm text-emerald-900">
            <p className="flex items-center gap-2 font-medium">
              <ShieldCheck className="h-4 w-4" />
              Compliance check attached: {answer.compliance.grade} (
              {Math.round(answer.compliance.compliance_score * 100)}/100)
            </p>
            <Link href="/compliance" className="mt-1 inline-block underline">
              Open the full gap report
            </Link>
          </div>
        ) : null}

        {answer.notes.length > 0 ? (
          <details className="rounded-md border bg-muted/30 p-3 text-xs text-muted-foreground">
            <summary className="flex cursor-pointer items-center gap-2 font-medium text-foreground">
              <Info className="h-3.5 w-3.5" />
              How this answer was produced ({answer.notes.length} steps)
            </summary>
            <ul className={cn("mt-2 list-disc space-y-1 pl-5")}>
              {answer.notes.map((note) => (
                <li key={note}>{note}</li>
              ))}
            </ul>
          </details>
        ) : null}

        {/* Download Procurement Report Actions */}
        <Separator className="my-2" />
        <div className="flex flex-wrap items-center justify-between gap-3 pt-1">
          <span className="text-xs font-medium text-muted-foreground">
            Download Procurement Assessment:
          </span>
          <div className="flex items-center gap-2">
            <Button
              variant="outline"
              size="sm"
              className="h-8 px-3 text-xs font-medium gap-1.5 hover:border-blue-500 hover:text-blue-600 dark:hover:text-blue-400"
              disabled={exportingFormat !== null}
              onClick={() => handleExport("docx")}
              title="Download formatted Word document"
            >
              {exportingFormat === "docx" ? (
                <Loader2 className="h-3.5 w-3.5 animate-spin text-blue-600" />
              ) : (
                <FileText className="h-3.5 w-3.5 text-blue-600" />
              )}
              <span>Download DOCX</span>
            </Button>

            <Button
              variant="outline"
              size="sm"
              className="h-8 px-3 text-xs font-medium gap-1.5 hover:border-red-500 hover:text-red-600 dark:hover:text-red-400"
              disabled={exportingFormat !== null}
              onClick={() => handleExport("pdf")}
              title="Download formatted PDF document"
            >
              {exportingFormat === "pdf" ? (
                <Loader2 className="h-3.5 w-3.5 animate-spin text-red-600" />
              ) : (
                <FileText className="h-3.5 w-3.5 text-red-600" />
              )}
              <span>Download PDF</span>
            </Button>
          </div>
        </div>

        {exportError && (
          <div className="rounded-md border border-destructive/30 bg-destructive/10 p-2 text-xs text-destructive">
            {exportError}
          </div>
        )}
      </CardContent>
    </Card>
  );
}
