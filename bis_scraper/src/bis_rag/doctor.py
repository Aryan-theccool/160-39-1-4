# rendering
# ----------------------------------------------------------------------
def doctor_payload(corpus: CorpusFacts, store: StoreFacts,
                   provenance: ProvenanceFacts, *, embedder: str = "",
                   backends: Optional[list[str]] = None) -> dict[str, Any]:
    """Everything doctor prints, as data, so the artifacts can carry it too."""
    return {
        "data_dir": str(corpus.root),
        "store_dir": str(store.path),
        "corpus": {
            "exists": corpus.exists,
            "standards": corpus.standards,
            "chunks": corpus.chunks,
            "divisions": corpus.divisions,
            "committees": corpus.committees,
            "current": corpus.current,
            "superseded": corpus.superseded,
            "compulsory": corpus.compulsory,
            "year_range": list(corpus.year_range),
            "tfidf_index": corpus.tfidf_index,
            "error": corpus.error,
        },
        "vector_store": {
            "path": str(store.path),
            "exists": store.exists,
            "backend": store.backend,
            "embedder": store.embedder_name,
            "fingerprint": store.embedder_fingerprint,
            "dim": store.dim,
            "total_vectors": store.total_vectors,
            "collections": [
                {"name": c.name, "level": c.level, "count": c.count,
                 "backend": c.backend, "error": c.error}
                for c in store.collections
            ],
        },
        "embedder_requested": embedder,
        "available_backends": backends if backends is not None else available_backends(),
        "provenance": provenance.as_dict(),
    }


def format_doctor(payload: dict[str, Any]) -> str:
    """Render :func:`doctor_payload` for a terminal."""
    corpus = payload["corpus"]
    store = payload["vector_store"]
    provenance = payload["provenance"]
    lines: list[str] = ["bis-rag doctor", ""]

    kind = provenance["kind"]
    # With no directory at all, "REAL CORPUS" was the one thing the banner must
    # not say: the absence of a fixture is not the presence of data.
    if not corpus["exists"]:
        kind = "no corpus"
    banner = f"  PROVENANCE : {kind.upper()}"
    if provenance["is_fixture"]:
        banner = f"  PROVENANCE : {kind.upper()}  <- NOT PRODUCTION DATA"
    lines += [banner,
              f"  data dir   : {payload['data_dir']}",
              f"  store dir  : {payload['store_dir']}", ""]
    if provenance["marker"]:
        lines.append(f"  fixture marker: {provenance['marker']}")
        generator = (provenance.get("detail") or {}).get("generator")
        if generator:
            lines.append(f"  generated by  : {generator}")
        lines.append("")

    lines.append("Corpus")
    if not corpus["exists"]:
        lines.append("  data directory does not exist")
    elif corpus["error"]:
        lines.append(f"  unreadable: {corpus['error']}")
    else:
        lines.append(f"  standards        {corpus['standards']}")
        lines.append(f"  chunks           {corpus['chunks']}")
        lines.append(f"  divisions        {corpus['divisions']}")
        lines.append(f"  committees       {corpus['committees']}")
        lines.append(f"  current          {corpus['current']}")
        lines.append(f"  superseded       {corpus['superseded']}")
        lines.append(f"  compulsory       {corpus['compulsory']}")
        low, high = corpus["year_range"]
        lines.append(f"  year range       {low}-{high}" if low else "  year range       unknown")
        lines.append(f"  tf-idf index     {'present' if corpus['tfidf_index'] else 'absent'}")

    lines += ["", "Vector store"]
    if not store["exists"]:
        lines.append(f"  {store['path']} does not exist -- run `bis-rag build`")
    else:
        lines.append(f"  backend          {store['backend']}")
        lines.append(f"  embedder         {store['embedder'] or 'unrecorded'}"
                     + (f" (dim={store['dim']})" if store["dim"] else ""))
        if store["fingerprint"]:
            lines.append(f"  fingerprint      {store['fingerprint']}")
        lines.append(f"  collections      {len(store['collections'])}"
                     f"   total vectors {store['total_vectors']}")
        for collection in store["collections"]:
            if collection["error"]:
                lines.append(f"    {collection['name']:<16} (level={collection['level']})"
                             f"  unavailable: {collection['error']}")
            else:
                lines.append(f"    {collection['name']:<16} (level={collection['level']})"
                             f"  {collection['count']} vectors")

    lines += ["", "Environment",
              f"  embedder requested : {payload['embedder_requested'] or '(config default)'}",
              f"  store backends     : {', '.join(payload['available_backends'])}"]

    warning = provenance.get("warning") or _provenance_warning(provenance)
    if warning:
        lines += ["", "WARNING:", "  " + warning.replace("\n", "\n  ")]
    return "\n".join(lines) + "\n"


def _provenance_warning(provenance: dict[str, Any]) -> str:
    if provenance.get("is_fixture"):
        return (f"synthetic fixture: {provenance.get('standards')} generated standards. "
                f"Numbers from this corpus describe the fixture, not the engine.")
    if provenance.get("suspiciously_small"):
        return (f"only {provenance.get('standards')} standards, below the "
                f"{MIN_PRODUCTION_STANDARDS}-standard floor for certification.")
    return ""
